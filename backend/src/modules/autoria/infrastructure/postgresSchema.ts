import { sql } from "../../../infrastructure/postgres";
import { AUTORES } from "./schema";

/** A mesma tabela `autores` do SQLite — e a mesma carga inicial. */
export async function createAutoriaTablesPostgres(): Promise<void> {
  await sql`
    CREATE TABLE IF NOT EXISTS autores (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nome TEXT NOT NULL,
      orcid TEXT UNIQUE,
      tipo TEXT NOT NULL DEFAULT 'literatura',
      livros_no_acervo INTEGER NOT NULL DEFAULT 0
    )
  `;

  for (const [id, nome, tipo] of AUTORES) {
    await sql`
      INSERT INTO autores (id, nome, tipo) VALUES (${id}, ${nome}, ${tipo})
      ON CONFLICT (id) DO NOTHING
    `;
  }

  // os ids da carga foram dados à mão: a sequência precisa saber, senão o
  // próximo autor cadastrado tentaria o id 1 de novo
  await sql`
    SELECT setval(pg_get_serial_sequence('autores', 'id'), (SELECT MAX(id) FROM autores))
  `;
}
